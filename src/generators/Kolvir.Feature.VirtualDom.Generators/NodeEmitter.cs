using System.Text;

namespace Kolvir.Feature.VirtualDom.Generators;

/// <summary>Writes the node classes for one manifest.</summary>
internal static class NodeEmitter
{
    internal static void Write(ManifestModel manifest, StringBuilder source)
    {
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("// Generated by Kolvir.Feature.VirtualDom.Generators. Do not edit.");
        source.AppendLine("#nullable enable");
        source.AppendLine("#pragma warning disable CS1591, CS8600, CS8601, CS8602, CS8603, CS8604, CS8619, CS8620");
        source.AppendLine();

        var indent = string.Empty;

        if (manifest.Namespace is { } ns)
        {
            source.AppendLine("namespace " + ns);
            source.AppendLine("{");
            indent = "    ";
        }

        foreach (var control in manifest.Controls)
        {
            WriteNode(control, source, indent);
            source.AppendLine();
        }

        if (manifest.Namespace is not null)
        {
            source.AppendLine("}");
        }
    }

    private static void WriteNode(ControlModel control, StringBuilder source, string indent)
    {
        var inner = indent + "    ";
        var body = inner + "    ";

        source.AppendLine(indent + "/// <summary>A node that makes a " + control.ControlType + ".</summary>");
        if (!control.AcceptsChildren)
        {
            source.AppendLine(indent + "[global::Kolvir.Feature.VirtualDom.LeafNode]");
        }

        source.AppendLine(indent + control.Accessibility + " sealed class " + control.NodeName + " : global::Kolvir.Feature.VirtualDom.VNode");
        source.AppendLine(indent + "{");
        source.AppendLine(body + "private static readonly global::Kolvir.Feature.VirtualDom.NodeType Kind =");
        source.AppendLine(body + "    new global::Kolvir.Feature.VirtualDom.NodeType(");
        source.AppendLine(body + "        typeof(" + control.ControlType + "),");
        source.AppendLine(body + "        () => new " + control.ControlType + "());");

        if (control.Properties.Any(property => property.Pristine is not null))
        {
            // One control answers for every pristine value a node type needs. Reading them off a
            // thrown-away instance per property would construct a control per property at type load,
            // and controls are not free; declaration order is what makes the shared one available
            // before the fields that read it.
            source.AppendLine();
            source.AppendLine(body + "private static readonly " + control.ControlType + " Pristine =");
            source.AppendLine(body + "    new " + control.ControlType + "();");
        }

        foreach (var property in control.Properties)
        {
            if (property.Pristine is { } pristine)
            {
                source.AppendLine();
                source.AppendLine(body + "private static readonly " + property.Type + " " + pristine + " = Pristine." + property.Name + ";");
            }
        }

        foreach (var property in control.Properties)
        {
            source.AppendLine();
            source.AppendLine(body + "private global::Kolvir.Feature.VirtualDom.Specified<" + property.Type + "> " + property.Field + ";");
            source.AppendLine(body + "public " + property.Type + " " + property.Name);
            source.AppendLine(body + "{");
            source.AppendLine(body + "    get => " + property.Field + ".Value;");
            // Constructed rather than assigned: a user-defined implicit conversion is only considered
            // when the source converts to the operator's parameter by a standard conversion, and it is
            // not for a nullable reference type argument, where the operator takes the very type it
            // was handed. A constructor call says the same thing and has no such rule to satisfy.
            source.AppendLine(
                body + "    set => " + property.Field + " = new global::Kolvir.Feature.VirtualDom.Specified<" + property.Type + ">(value);");
            source.AppendLine(body + "}");
        }

        source.AppendLine();
        source.AppendLine(body + "public override global::Kolvir.Feature.VirtualDom.NodeType NodeType => Kind;");

        WriteApply(control, source, body);
        WritePatch(control, source, body);

        source.AppendLine(indent + "}");
    }

    private static void WriteApply(ControlModel control, StringBuilder source, string body)
    {
        source.AppendLine();
        source.AppendLine(body + "public override void ApplyTo(global::Kolvir.Control control)");
        source.AppendLine(body + "{");
        source.AppendLine(body + "    var target = (" + control.ControlType + ")control;");

        foreach (var property in control.Properties)
        {
            if (property.IsEvent)
            {
                source.AppendLine(body + "    if (" + property.Field + ".IsSpecified && " + property.Field + ".Value is { } " + property.Field + "Value)");
                source.AppendLine(body + "    {");
                source.AppendLine(body + "        target." + property.AddHandler + "(" + property.Field + "Value);");
                source.AppendLine(body + "    }");
            }
            else
            {
                source.AppendLine(body + "    if (" + property.Field + ".IsSpecified)");
                source.AppendLine(body + "    {");
                source.AppendLine(body + "        target." + property.Name + " = " + property.Field + ".Value;");
                source.AppendLine(body + "    }");
            }
        }

        source.AppendLine(body + "}");
    }

    private static void WritePatch(ControlModel control, StringBuilder source, string body)
    {
        source.AppendLine();
        source.AppendLine(body + "public override void PatchFrom(global::Kolvir.Feature.VirtualDom.VNode previous, global::Kolvir.Control control)");
        source.AppendLine(body + "{");
        source.AppendLine(body + "    var old = (" + control.NodeName + ")previous;");
        source.AppendLine(body + "    var target = (" + control.ControlType + ")control;");

        foreach (var property in control.Properties)
        {
            source.AppendLine();
            source.AppendLine(body + "    if (!" + property.Field + ".Equals(old." + property.Field + "))");
            source.AppendLine(body + "    {");

            if (property.IsEvent)
            {
                source.AppendLine(body + "        if (old." + property.Field + ".IsSpecified && old." + property.Field + ".Value is { } detached" + property.Name + ")");
                source.AppendLine(body + "        {");
                source.AppendLine(body + "            target." + property.RemoveHandler + "(detached" + property.Name + ");");
                source.AppendLine(body + "        }");
                source.AppendLine();
                source.AppendLine(body + "        if (" + property.Field + ".IsSpecified && " + property.Field + ".Value is { } attached" + property.Name + ")");
                source.AppendLine(body + "        {");
                source.AppendLine(body + "            target." + property.AddHandler + "(attached" + property.Name + ");");
                source.AppendLine(body + "        }");
            }
            else
            {
                source.AppendLine(
                    body + "        target." + property.Name + " = " + property.Field + ".IsSpecified ? " + property.Field + ".Value : " + property.Pristine + ";");
            }

            source.AppendLine(body + "    }");
        }

        source.AppendLine(body + "}");
    }
}
